// The committed setup context (`.rca-context.json`) — find, read, select a
// profile, and write one connector at a time.
//
// THREE THINGS THIS FILE DELIBERATELY DOES NOT DO.
//
// 1. It does not harden what it writes. Every other persisted artifact in lib/
//    (csv-state, evidence-file, turn1-registry, tool-cache) creates 0700
//    directories and 0600 files, and state-dir sweeps the tree to match. That is
//    right for OS-temp run state and wrong for this one: the context is
//    git-tracked, git does not preserve the mode, and a 0600 file inside a repo
//    is a confusing artifact rather than a protected one. `hardenStateDir` must
//    never be pointed here, and there is no chmod below.
//
// 2. It does not detect credentials. There is no looksLikeSecret, no entropy
//    check, no provider-prefix table, no pattern over content. Deciding whether
//    a string is a secret is a judgement, and the four times this project
//    encoded that judgement in a pattern it broke. What replaces it is shape:
//    `credential` is only {kind:"env-var", name} or {kind:"provider-managed"},
//    every closed object below validates its keys against an allowlist, and the
//    schema has no field a value belongs in. The rest is prompt discipline in
//    skills/rca-build/references/interview.md.
//
// 3. It never executes `howToQuery`. That field is stored structured
//    ({tool, args[]}) as DOCUMENTATION: the agent reads it and re-authors its own
//    call under the user's permission layer. If this module shelled it, a PR
//    editing a file reviewers skim as config would change what commands run. The
//    only child_process use here is the `git` needed to resolve worktrees and
//    tracked-ness.
//
// Dates are always injected (`todayISO`). Nothing below reads the clock, so
// selection and staleness are deterministic in tests and usable from the
// auto-mode sandbox.

